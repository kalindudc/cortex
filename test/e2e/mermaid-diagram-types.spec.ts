// E2E coverage for mermaid diagram-type renderer plumbing.
//
// Why this exists (regression guard):
//
//   Mermaid 11 self-registers its diagram renderers via async `import()`
//   from per-type chunks (`stateDiagram-v2-*.mjs`, `flowchart-v2-*.mjs`,
//   etc.). Bundling mermaid through `bun build` (as cortex used to do for
//   `out/mermaid.js`) silently drops most of those chunks: the registrar
//   still installs detectors so `mermaid.parse()` accepts the input, but
//   at render time the per-type renderer dereferences `undefined` and
//   throws `K.render is not a function`. Sequence + gantt happened to get
//   bundled correctly, so the prior `render-markdown.spec.ts` test (which
//   only used `graph LR` and only asserted "some <svg> appears" — true
//   even for mermaid's error icon) failed to catch this.
//
//   Cortex now ships mermaid's pre-built `dist/` tree verbatim via 217
//   `with { type: "file" }` imports generated by
//   `scripts/gen-mermaid-manifest.ts`, served as embedded blobs under
//   `/mermaid/...`. This test exercises five diagram types end to end
//   (flowchart, stateDiagram-v2, sequenceDiagram, classDiagram, pie) and
//   asserts each one produces a real diagram SVG — not mermaid's
//   "Syntax error in text" bomb-icon SVG.
//
//   Discrimination: a successful render embeds the diagram's text labels
//   into the SVG's textContent. The error SVG textContent contains the
//   literal "Syntax error in text". So the assertions are (a) the rendered
//   SVG textContent contains a label unique to the diagram source, and
//   (b) it does NOT contain "Syntax error".

import { expect, type Locator } from "@playwright/test";
import { test as base } from "./fixtures/cortex-server.ts";

const extendedTest = base.extend({});

async function seedLane(url: string, name: string): Promise<void> {
  const r = await fetch(`${url}/api/lanes`, {
    method: "POST",
    headers: { "content-type": "application/json" },
    body: JSON.stringify({ name }),
  });
  if (!r.ok) throw new Error(`failed to seed lane ${name}: ${r.status} ${await r.text()}`);
}

async function seedTask(
  url: string,
  lane: string,
  title: string,
  body: string,
): Promise<{ id: number; title: string }> {
  const r = await fetch(`${url}/api/tasks`, {
    method: "POST",
    headers: { "content-type": "application/json" },
    body: JSON.stringify({ lane, title, body }),
  });
  if (!r.ok) throw new Error(`failed to seed task: ${r.status} ${await r.text()}`);
  return r.json();
}

// Diagram-type matrix. Each entry seeds a fence in the rendered body and
// asserts a unique-to-this-diagram label round-trips into the SVG textContent.
//
// The labels (FlowProbeNode, StateProbeAlpha, etc.) are arbitrary but
// MUST be unique across the matrix so a regression that wires Block N's
// renderer to Block M's source still fails.
interface DiagramCase {
  type: string; // human label only
  fence: string; // body between the ```mermaid fences
  probe: string; // label that must appear in the rendered SVG textContent
}

const CASES: DiagramCase[] = [
  {
    type: "flowchart",
    fence: ["flowchart LR", '  A["FlowProbeNode"] --> B["FlowProbeEdge"]'].join("\n"),
    probe: "FlowProbeNode",
  },
  {
    type: "stateDiagram-v2",
    fence: ["stateDiagram-v2", "    [*] --> StateProbeAlpha", "    StateProbeAlpha --> [*]"].join("\n"),
    probe: "StateProbeAlpha",
  },
  {
    type: "sequenceDiagram",
    fence: ["sequenceDiagram", "    SeqProbeActor->>SeqProbeTarget: hi"].join("\n"),
    probe: "SeqProbeActor",
  },
  {
    type: "classDiagram",
    fence: ["classDiagram", "    class ClassProbeFoo { +bar() }"].join("\n"),
    probe: "ClassProbeFoo",
  },
  {
    type: "pie",
    fence: ["pie title PieProbeTitle", '  "PieProbeSlice" : 1'].join("\n"),
    probe: "PieProbeSlice",
  },
];

function buildBody(): string {
  // Number the fences in the source so a failure message points to the
  // right block even if the markdown renderer reorders them (it doesn't,
  // but the comments serve as a sanity anchor in test output).
  const sections: string[] = ["# Mermaid diagram type matrix", ""];
  CASES.forEach((c, i) => {
    sections.push(`## Block ${i + 1} — ${c.type}`);
    sections.push("");
    sections.push("```mermaid");
    sections.push(c.fence);
    sections.push("```");
    sections.push("");
  });
  return sections.join("\n");
}

extendedTest("every mermaid diagram type renders to a real SVG (not the error bomb)", async ({ url, page }) => {
  await seedLane(url, "inbox");
  await seedTask(url, "inbox", "mermaid-matrix", buildBody());

  await page.goto(url);
  await page.locator(".task-row", { hasText: "mermaid-matrix" }).click();
  await page.locator('.active-header button[title="Render markdown"]').click();
  await expect(page.locator(".modal--wide")).toBeVisible();

  // Wait for all N mermaid blocks to have an SVG at all. mermaid.run()
  // processes them in batch; auto-wait on count covers the lazy import +
  // parse + render round-trip without a fixed sleep.
  const allSvgs = page.locator(".markdown-rendered pre.mermaid svg");
  await expect(allSvgs).toHaveCount(CASES.length, { timeout: 20_000 });

  // Now assert each block individually: probe label present, no error text.
  const blocks = page.locator(".markdown-rendered pre.mermaid");
  for (let i = 0; i < CASES.length; i++) {
    const c = CASES[i];
    const block: Locator = blocks.nth(i);
    const svg = block.locator("svg");
    await expect(svg, `${c.type} (block ${i + 1}): SVG missing`).toBeVisible();

    // Mermaid's error SVG contains the literal "Syntax error in text".
    // Successful renders never carry that string. Assertion order matters:
    // check for the error text FIRST so its absence is a precondition for
    // the probe assertion.
    const svgText = (await svg.textContent()) ?? "";
    expect(
      svgText,
      `${c.type} (block ${i + 1}): SVG textContent matched mermaid error icon — bundle is missing this diagram type's renderer`,
    ).not.toContain("Syntax error");
    expect(
      svgText,
      `${c.type} (block ${i + 1}): SVG textContent missing probe label "${c.probe}" — diagram rendered but content is wrong`,
    ).toContain(c.probe);
  }
});
