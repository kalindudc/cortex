// Markdown rendering pipeline shared by every rendered-Markdown surface
// (task reading, expanded update bodies, the legacy modal viewers).
//
// SECURITY MODEL: Marked does NOT sanitize. Every parse
// result is sanitized with DOMPurify BEFORE insertion using an HTML profile
// with SANITIZE_NAMED_PROPS; executable/embedding/form elements and raw
// SVG/MathML are forbidden, style/data attributes are stripped, and link
// URLs must be http(s)/mailto/relative. Mermaid fence TEXT is HTML-escaped
// into `<pre class="mermaid">` (textContent recovers the raw `-->`/`<`
// arrows), rendered offscreen via mermaid.render, and the returned SVG is
// sanitized with an SVG profile before it touches the live DOM. The stored
// Markdown itself is NEVER rewritten.
//
// Mermaid is loaded as a SEPARATE prebuilt dist (copied into out/ui/mermaid
// by scripts/copy-mermaid.ts and served at /mermaid/* by the desktop app's
// cortex:// handler) on the first runMermaid call that actually
// sees a diagram — source-only documents never pay the module cost. A
// failed module load is NOT cached; the next call retries.
//
// Diagrams are drawn in Mermaid's hand-drawn look with a fixed seed, in the
// ink of the current palette (resolved CSS tokens) with --font-serif labels;
// see mermaidConfig.

import { marked } from "marked";
import DOMPurify from "dompurify";
import type { Config as DOMPurifyConfig } from "dompurify";
import type { MermaidConfig } from "mermaid";

// Thrown when the environment cannot provide a working sanitizer
// (DOMPurify.isSupported false). Callers MUST fail closed: show the raw
// source and an explicit error — never insert unsanitized HTML.
export class MarkdownUnsupportedError extends Error {
  constructor() {
    super("Markdown sanitizer is not supported in this environment");
    this.name = "MarkdownUnsupportedError";
  }
}

// Allow http(s)/mailto absolute URLs and anything WITHOUT a scheme
// (relative paths, #fragments, ?queries). Every other scheme — javascript:,
// data:, vbscript:, file:, blob:, … — is rejected. DOMPurify strips
// control characters before testing, so `java\nscript:` normalizes first.
const SAFE_URI_RE = /^(?:(?:https?|mailto):|(?![a-z][a-z0-9+.-]*:))/i;

// HTML profile: safe GFM/HTML structure only.
//   USE_PROFILES html  — no raw SVG/MathML pass-through.
//   FORBID_TAGS        — executable / embedding / form / style surfaces,
//                        listed explicitly for defense in depth even where
//                        the profile already excludes them.
//   FORBID_ATTR style  + ALLOW_DATA_ATTR false — strip style/data-*.
//   SANITIZE_NAMED_PROPS — prefix id/name to block DOM clobbering.
const HTML_SANITIZE_CONFIG: DOMPurifyConfig = {
  USE_PROFILES: { html: true },
  FORBID_TAGS: [
    "style",
    "script",
    "iframe",
    "object",
    "embed",
    "form",
    "button",
    "textarea",
    "select",
    "option",
    "svg",
    "math",
    "link",
    "meta",
    "base",
    "dialog",
  ],
  FORBID_ATTR: ["style"],
  ALLOW_DATA_ATTR: false,
  SANITIZE_NAMED_PROPS: true,
  ALLOWED_URI_REGEXP: SAFE_URI_RE,
};

// SVG profile: applied to mermaid.render output before insertion.
// <style> stays allowed — mermaid themes its diagrams through an embedded
// style element and the content is generated by mermaid from our secure
// config, not by the document author. foreignObject (HTML-in-SVG) is
// forbidden; htmlLabels is disabled so mermaid should never emit it.
//
// SANITIZE_NAMED_PROPS is deliberately OFF here: it rewrites every id to
// `user-content-*`, but mermaid's embedded <style> is scoped by the root id
// and its arrowheads are `url(#id)` marker references — rewriting the ids
// breaks both (Chromium e2e showed black boxes with no edges). Clobber
// protection for this pass is the `uponSanitizeAttribute` hook below, which
// drops any id/name that shadows a window/document property. Mermaid also
// prefixes author-controlled identifiers itself (flowchart-<id>-<n>, ...).
const SVG_SANITIZE_CONFIG: DOMPurifyConfig = {
  USE_PROFILES: { svg: true, svgFilters: true },
  ADD_TAGS: ["style"],
  FORBID_TAGS: ["foreignobject", "script", "iframe", "form", "audio", "video"],
  ALLOW_DATA_ATTR: false,
  ALLOWED_URI_REGEXP: SAFE_URI_RE,
};

// True only while the SVG pass runs — the hook below is per-instance, so
// it needs to know which profile is active.
let svgPass = false;

function escapeHtml(s: string): string {
  return s
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;")
    .replace(/'/g, "&#39;");
}

// One-time marked + DOMPurify configuration.
//
// `configured` guards the marked.use({...}) call so each render doesn't
// re-register renderer overrides, and the DOMPurify hook so it stacks once.
let configured = false;
function configureOnce(): void {
  if (configured) return;
  configured = true;
  marked.use({
    gfm: true,
    breaks: false,
    renderer: {
      // v15 renderer signature: token object, NOT positional (code, lang).
      // Returning `false` falls through to marked's default renderer.
      // Mermaid fence text is HTML-ESCAPED — the browser's parser decodes
      // the entities back into text content on insertion, so
      // `.textContent` recovers the raw source (arrows, angle brackets)
      // without ever letting the fence inject markup.
      code({ text, lang }: { text: string; lang?: string }) {
        if (lang === "mermaid") {
          return `<pre class="mermaid">${escapeHtml(text)}</pre>`;
        }
        return false;
      },
    },
  });
  // Only DISABLED task-list checkboxes survive as inputs: any other
  // input flavor is removed during sanitization, and surviving checkboxes
  // are forced disabled so rendered Markdown can never submit/focus-trap.
  DOMPurify.addHook("afterSanitizeAttributes", node => {
    if (node.tagName === "INPUT") {
      if ((node.getAttribute("type") ?? "").toLowerCase() !== "checkbox") {
        node.remove();
        return;
      }
      node.setAttribute("disabled", "");
    }
  });
  // SVG pass clobber guard (see SVG_SANITIZE_CONFIG): named access on
  // window/document must never be shadowed by a diagram element id.
  DOMPurify.addHook("uponSanitizeAttribute", (_node, data) => {
    if (!svgPass) return;
    if (data.attrName !== "id" && data.attrName !== "name") return;
    const v = data.attrValue;
    if (v in window || v in document) data.keepAttr = false;
  });
}

/**
 * Render a markdown string to SANITIZED HTML.
 *
 * Synchronous (marked.parse with `async: false` defaults). Mermaid code
 * fences are HTML-escaped inside `<pre class="mermaid">`; `runMermaid`
 * later converts them to sanitized SVG after the HTML is in the DOM.
 *
 * Throws MarkdownUnsupportedError when no working sanitizer exists —
 * callers render an explicit source/error view instead (fail closed).
 */
export function renderMarkdown(md: string): string {
  configureOnce();
  if (!DOMPurify.isSupported) throw new MarkdownUnsupportedError();
  const raw = marked.parse(md) as string;
  return DOMPurify.sanitize(raw, HTML_SANITIZE_CONFIG);
}

