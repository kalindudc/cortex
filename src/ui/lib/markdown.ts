// Diagram lifecycle state written onto each `pre.mermaid` node:
//   (none)  — source visible, never attempted
//   done    — sanitized SVG committed; data-mermaid-theme records which
//             theme produced it so theme flips re-render only stale nodes
//   error   — render/load failed; raw source stays visible and
//             data-mermaid-error carries the message. Callers surface an
//             explicit retry affordance (MarkdownView does).
export type MermaidState = "done" | "error";

let mermaidPromise: Promise<typeof import("mermaid").default> | null = null;

// Serialize EVERY initialize+render batch as one job (M3): mermaid's API
// queues render calls but initialize is global — interleaving a theme
// change between another job's initialize and render would render with the
// wrong config. The chain never rejects (failures are surfaced per call).
let jobChain: Promise<unknown> = Promise.resolve();
function enqueue<T>(job: () => Promise<T>): Promise<T> {
  const next = jobChain.then(job, job);
  jobChain = next.then(
    () => undefined,
    () => undefined,
  );
  return next;
}

function detectTheme(): "dark" | "default" {
  if (typeof document === "undefined") return "default";
  return document.documentElement.dataset.theme === "dark" ? "dark" : "default";
}

async function loadMermaid(): Promise<typeof import("mermaid").default> {
  if (!mermaidPromise) {
    // Dynamic-import target is the BROWSER URL `/mermaid/mermaid.esm.min.mjs`,
    // NOT the npm specifier "mermaid" — the npm specifier would inline the
    // module into bundle.js and defeat the lazy dist passthrough (see
    // src/server.ts MERMAID_ASSETS). `new URL(...)` keeps Bun's bundler from
    // statically resolving the target.
    const url = new URL("/mermaid/mermaid.esm.min.mjs", document.baseURI).href;
    mermaidPromise = import(url).then((mod: { default: typeof import("mermaid").default }) => mod.default);
  }
  try {
    return await mermaidPromise;
  } catch (err) {
    // Do NOT cache the rejection — the next call retries the fetch (M3).
    mermaidPromise = null;
    throw err;
  }
}

let renderSeq = 0; // job tokens (one per runMermaid call)
let idSeq = 0; // unique DOM ids for mermaid.render

/**
 * Convert `<pre class="mermaid">` blocks inside `root` into sanitized SVG.
 *
 * - No diagrams in `root` → resolves immediately WITHOUT loading mermaid.
 * - Renders happen inside an inert offscreen staging element via
 *   mermaid.render; the returned SVG is sanitized with the SVG profile
 *   before insertion. Diagram callbacks are never bound.
 * - `isCurrent` (plus node connectivity) gates every commit: obsolete
 *   generations are discarded instead of clobbering newer renders.
 * - Per-diagram failures mark the node (`data-mermaid-state="error"`,
 *   `data-mermaid-error=<msg>`) and leave the source visible; the promise
 *   REJECTS on module-load failure so callers can show an explicit
 *   error/retry. No silent success on failure.
 * - Nodes already rendered for the current theme are skipped, so theme
 *   changes regenerate only diagrams that need it.
 */
export async function runMermaid(root: HTMLElement, isCurrent?: () => boolean): Promise<void> {
  const theme = detectTheme();
  const pending = Array.from(root.querySelectorAll<HTMLElement>("pre.mermaid")).filter(node => {
    const state = node.dataset.mermaidState;
    if (state === "done") return node.dataset.mermaidTheme !== theme; // theme-stale only
    return state !== "error"; // untouched nodes; errors wait for explicit retry
  });
  if (pending.length === 0) return;

  // Stash the raw source (textContent decodes the escaped entities) and
  // stamp this run's job token before yielding to the queue — a newer run
  // targeting the same node overwrites the token and this run's commit is
  // discarded below.
  const jobId = String(++renderSeq);
  const sources = new Map<HTMLElement, string>();
  for (const node of pending) {
    const source = node.dataset.mermaidSource ?? node.textContent ?? "";
    node.dataset.mermaidSource = source;
    node.dataset.mermaidJob = jobId;
    sources.set(node, source);
  }

  await enqueue(async () => {
    if (!DOMPurify.isSupported) throw new MarkdownUnsupportedError();
    const mermaid = await loadMermaid(); // rejects propagate to the caller
    mermaid.initialize({
      startOnLoad: false,
      securityLevel: "strict",
      htmlLabels: false,
      flowchart: { htmlLabels: false },
      theme,
      // Protect security/label/style config from in-diagram directives (M3).
      secure: [
        "secure",
        "securityLevel",
        "startOnLoad",
        "maxTextSize",
        "htmlLabels",
        "theme",
        "themeCSS",
        "themeVariables",
        "fontFamily",
      ],
    });

    // Inert offscreen staging container — NEVER the live reader (M3).
    const staging = document.createElement("div");
    staging.setAttribute("aria-hidden", "true");
    staging.style.cssText = "position:absolute;left:-99999px;top:0;width:800px;visibility:hidden;pointer-events:none;";
    document.body.appendChild(staging);
    try {
      for (const node of pending) {
        const source = sources.get(node) ?? "";
        const stillWanted = (): boolean =>
          node.isConnected && node.dataset.mermaidJob === jobId && (isCurrent?.() ?? true);
        if (!stillWanted()) continue;
        try {
          const { svg } = await mermaid.render(`cortex-mermaid-${++idSeq}`, source, staging);
          if (!stillWanted()) continue; // discard obsolete/disconnected generations
          svgPass = true;
          let clean: string;
          try {
            clean = DOMPurify.sanitize(svg, SVG_SANITIZE_CONFIG);
          } finally {
            svgPass = false;
          }
          node.innerHTML = clean;
          node.dataset.mermaidState = "done";
          node.dataset.mermaidTheme = theme;
          delete node.dataset.mermaidError;
        } catch (err) {
          if (!stillWanted()) continue;
          // Preserve the raw source with an explicit error state; the
          // caller renders the retry affordance.
          node.textContent = source;
          node.dataset.mermaidState = "error";
          node.dataset.mermaidError = err instanceof Error ? err.message : String(err);
        }
      }
    } finally {
      staging.remove();
    }
  });
}

/**
 * Reset a failed diagram node back to source-pending so the next
 * runMermaid attempt includes it (explicit retry path).
 */
export function resetMermaidNode(node: HTMLElement): void {
  node.textContent = node.dataset.mermaidSource ?? node.textContent ?? "";
  delete node.dataset.mermaidState;
  delete node.dataset.mermaidError;
  delete node.dataset.mermaidTheme;
}
