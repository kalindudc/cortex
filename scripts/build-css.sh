#!/usr/bin/env bash
# build-css.sh — Concatenate per-feature CSS slices into out/bundle.css.
#
# Why this script exists at all: Bun 1.1.12 (the pinned bundler) does NOT
# inline CSS `@import` statements AND clobbers same-named bundle.css outputs
# when multiple JS-side `import "./foo.css"` statements are reached, so we
# cannot rely on the bundler to merge our 14 feature slices.
#
# Why CSS is built outside `bun build`: src/server.ts imports out/bundle.css
# via `with { type: "file" }`, which returns a path the server reads at
# request time. Nothing requires the CSS to come from the JS bundler graph
# — it just needs to exist at out/bundle.css on disk. Owning the CSS pipeline
# with this script (instead of routing it through bun build via a JS-side
# import) keeps build artifacts out of src/ and removes a layer of bundler
# coupling.
#
# Cascade order matches what styles/index.css would have looked like under
# Bun >=1.2: tokens → base → layout → utilities (misc) → structural surfaces
# (sidebar, chips, popover, modal, palette) → semantic widgets (tag-pill,
# tag-picker, tooltip, inbox) → active-task pane last so its overrides win.
# DO NOT reorder without re-verifying the dashboard renders identically.
#
# When Bun >=1.2 is adopted (see future-improvements note on cortex task 24),
# this script can be retired in favour of an `@import`-based styles/index.css
# imported from src/ui/index.tsx.

set -euo pipefail

DIR="$(cd "$(dirname "$0")/.." && pwd)"
STYLES="$DIR/src/ui/styles"
OUT_DIR="$DIR/out"
OUT="$OUT_DIR/bundle.css"

# Cascade order — single source of truth.
SLICES=(
  tokens
  base
  layout
  misc
  sidebar
  chips
  popover
  modal
  palette
  tag-pill
  tag-picker
  tooltip
  inbox
  notifications
  active
)

# Verify every slice exists before we start writing.
for s in "${SLICES[@]}"; do
  if [[ ! -f "$STYLES/$s.css" ]]; then
    echo "build-css.sh: missing slice src/ui/styles/$s.css" >&2
    exit 1
  fi
done

mkdir -p "$OUT_DIR"

{
  echo "/* AUTO-GENERATED by scripts/build-css.sh — DO NOT EDIT.";
  echo " * Edit individual slices in src/ui/styles/{name}.css instead.";
  echo " * Cascade order is fixed in scripts/build-css.sh:SLICES. */";
  echo
  for s in "${SLICES[@]}"; do
    echo "/* ===== styles/$s.css ===== */"
    cat "$STYLES/$s.css"
    echo
  done
} > "$OUT"

echo "✓ Generated $OUT ($(wc -l < "$OUT") lines)"
