#!/usr/bin/env bash
# build-css.sh — Concatenate the per-feature CSS slices in src/ui/styles into
# out/ui/bundle.css, the one stylesheet src/ui/index.html links.
#
# The SLICES order below is the cascade contract: tokens → base → layout →
# utilities (misc) → structural surfaces → semantic widgets → active-task pane
# → document LAST so its reading overrides win; DO NOT reorder without
# re-verifying the dashboard renders identically.

set -euo pipefail

DIR="$(cd "$(dirname "$0")/.." && pwd)"
STYLES="$DIR/src/ui/styles"
OUT_DIR="$DIR/out/ui"
OUT="$OUT_DIR/bundle.css"

# Cascade order — single source of truth.
SLICES=(
  tokens
  base
  layout
  misc
  sidebar
  chips
  popover
  modal
  palette
  tag-pill
  tag-picker
  tooltip
  inbox
  notifications
  context
  panels
  active
  document
  motion
)

# Verify every slice exists before we start writing.
for s in "${SLICES[@]}"; do
  if [[ ! -f "$STYLES/$s.css" ]]; then
    echo "build-css.sh: missing slice src/ui/styles/$s.css" >&2
    exit 1
  fi
done

mkdir -p "$OUT_DIR"

{
  echo "/* AUTO-GENERATED by scripts/build-css.sh — DO NOT EDIT.";
  echo " * Edit individual slices in src/ui/styles/{name}.css instead.";
  echo " * Cascade order is fixed in scripts/build-css.sh:SLICES. */";
  echo
  for s in "${SLICES[@]}"; do
    echo "/* ===== styles/$s.css ===== */"
    cat "$STYLES/$s.css"
    echo
  done
} > "$OUT"

echo "✓ Generated $OUT ($(wc -l < "$OUT") lines)"
