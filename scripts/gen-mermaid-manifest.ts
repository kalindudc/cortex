// Generates src/ui/mermaid-manifest.generated.ts — one
// `import ... with { type: "file" }` per shipped mermaid file, plus an
// exported route → embedded-path map consumed by src/server.ts.
//
// Why codegen: Bun's `with { type: "file" }` requires a static string
// specifier so the bundler can statically discover what to embed in
// `bun build --compile`. We can't loop. We can't glob. So we enumerate
// the 217 runtime chunks mermaid ships, write an import per file, and
// build the route map at module-evaluation time.
//
// We ship only `.mjs` (and `.css` if any) — source maps and .d.ts files
// stay out of the binary (saves ~70 MB of embedded dead weight).
//
// The generated file is .gitignored and regenerated on every build by
// `scripts/build.sh`. Mermaid's chunk filenames carry a release-stable
// hash (e.g. `stateDiagram-v2-PT3EUVB6.mjs`) so the manifest only churns
// when mermaid is upgraded — desirable.

import { mkdirSync, readdirSync, writeFileSync, statSync } from "node:fs";
import path from "node:path";

const ROOT = path.resolve(import.meta.dir, "..");
const MERMAID_DIST = path.join(ROOT, "node_modules", "mermaid", "dist");
const OUT_FILE = path.join(ROOT, "src", "ui", "mermaid-manifest.generated.ts");

// File extensions we actually want at runtime. .d.ts and .d.mts are TypeScript
// declarations; .map is sourcemaps; .js (two files) are non-ESM legacy that
// our dynamic-import loader doesn't touch.
const RUNTIME_EXTS = new Set([".mjs", ".css"]);

function isRuntimeFile(file: string): boolean {
  if (file.endsWith(".d.mts") || file.endsWith(".d.ts")) return false;
  if (file.endsWith(".map")) return false;
  return RUNTIME_EXTS.has(path.extname(file));
}

function walk(dir: string, out: string[] = []): string[] {
  for (const entry of readdirSync(dir)) {
    const abs = path.join(dir, entry);
    if (statSync(abs).isDirectory()) {
      walk(abs, out);
    } else if (isRuntimeFile(entry)) {
      out.push(abs);
    }
  }
  return out;
}

function mimeFor(file: string): string {
  if (file.endsWith(".mjs")) return "application/javascript; charset=utf-8";
  if (file.endsWith(".css")) return "text/css; charset=utf-8";
  throw new Error(`unknown MIME for ${file}`);
}

const files = walk(MERMAID_DIST).sort();

if (files.length === 0) {
  console.error(`No runtime files found under ${MERMAID_DIST}.`);
  process.exit(1);
}

// All imports are relative to src/ui/mermaid-manifest.generated.ts which is
// two directories deep from the repo root (src/ui/...).
const SRC_UI_DIR = path.join(ROOT, "src", "ui");

const lines: string[] = [
  "// @ts-nocheck",
  "// AUTO-GENERATED by scripts/gen-mermaid-manifest.ts — DO NOT EDIT.",
  '// Regenerated on every build; .gitignored. Bun\'s `with { type: "file" }` rewrites',
  "// each import to an embedded blob path inside the compiled binary.",
  "",
];

const entries: { route: string; ident: string; mime: string }[] = [];

files.forEach((abs, i) => {
  const ident = `f_${i}`;
  const relImport = path.relative(SRC_UI_DIR, abs).split(path.sep).join("/");
  // The route mirrors the file's position under mermaid/dist/ rooted at
  // /mermaid/. Mermaid's own dynamic imports use relative paths like
  // `./chunks/mermaid.esm/foo.mjs` from its entry, so the directory shape
  // must be preserved verbatim.
  const distRel = path.relative(MERMAID_DIST, abs).split(path.sep).join("/");
  const route = `/mermaid/${distRel}`;
  lines.push(`import ${ident} from "./${relImport}" with { type: "file" };`);
  entries.push({ route, ident, mime: mimeFor(abs) });
});

lines.push("");
lines.push("export const MERMAID_ASSETS: Record<string, { path: string; type: string }> = {");
for (const e of entries) {
  lines.push(`  ${JSON.stringify(e.route)}: { path: ${e.ident}, type: ${JSON.stringify(e.mime)} },`);
}
lines.push("};");
lines.push("");

mkdirSync(path.dirname(OUT_FILE), { recursive: true });
writeFileSync(OUT_FILE, lines.join("\n"));

console.log(`Wrote ${OUT_FILE} (${files.length} mermaid runtime files mapped).`);
